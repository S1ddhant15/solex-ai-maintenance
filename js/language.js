// ============================================================
// TRANSLATE MAINTENANCE PHRASE
// ============================================================


function translateMaintenancePhrase(
    phraseKey
) {


    const phrase =
        samaMaintenancePhrases[
            phraseKey
        ];



    if(!phrase) {

        return phraseKey;

    }



    return (
        phrase[samaLanguage]
        ||
        phrase.en
    );

}



