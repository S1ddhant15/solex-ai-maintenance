// ============================================================
// TRANSLATION HELPER
// ============================================================


function t(key) {


    const language =
        samaTranslations[samaLanguage]
        ||
        samaTranslations.en;



    if(
        language[key] !== undefined
    ) {

        return language[key];

    }



    if(
        samaTranslations.en[key] !== undefined
    ) {

        return samaTranslations.en[key];

    }



    return key;

}



// ============================================================
// SET LANGUAGE
// ============================================================


function setSAMALanguage(languageCode) {


    if(
        !samaTranslations[languageCode]
    ) {

        languageCode = "en";

    }



    samaLanguage =
        languageCode;



    localStorage.setItem(
        "samaLanguage",
        languageCode
    );



    applySAMALanguage();



    if(
        typeof refreshSAMAWelcome === "function"
    ) {

        refreshSAMAWelcome();

    }

}



// ============================================================
// GET CURRENT LANGUAGE
// ============================================================


function getSAMALanguage() {

    return samaLanguage;

}



// ============================================================
// LOAD SAVED LANGUAGE
// ============================================================


function loadSAMALanguage() {


    const saved =
        localStorage.getItem(
            "samaLanguage"
        );



    if(
        saved &&
        samaTranslations[saved]
    ) {

        samaLanguage =
            saved;

    }

}



// ============================================================
// APPLY LANGUAGE TO PAGE
// ============================================================


function applySAMALanguage() {


    document
        .querySelectorAll(
            "[data-i18n]"
        )
        .forEach(element => {


            const key =
                element.getAttribute(
                    "data-i18n"
                );


            if(key) {

                element.textContent =
                    t(key);

            }

        });



    document
        .querySelectorAll(
            "[data-i18n-placeholder]"
        )
        .forEach(element => {


            const key =
                element.getAttribute(
                    "data-i18n-placeholder"
                );


            if(key) {

                element.placeholder =
                    t(key);

            }

        });



    const languageSelector =
        document.getElementById(
            "languageSelector"
        );



    if(languageSelector) {

        languageSelector.value =
            samaLanguage;

    }

}



